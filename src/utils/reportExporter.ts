import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import * as XLSX from 'xlsx';
import {
  Document,
  Packer,
  Paragraph,
  Table,
  TableRow,
  TableCell,
  TextRun,
  WidthType,
  AlignmentType,
  HeadingLevel,
  BorderStyle,
  ShadingType
} from 'docx';

export interface ReportExportOptions {
  businessName: string;
  businessAddress?: string;
  businessTaxId?: string;
  reportTitle: string;
  startDate: string;
  endDate: string;
  filenamePrefix: string;
  headers: string[];
  rows: (string | number)[][];
  summaryRows?: Array<{ label: string; value: string | number }>;
  columnAlignments?: readonly ('left' | 'center' | 'right')[] | ('left' | 'center' | 'right')[];
}

const downloadBlob = (blob: Blob, filename: string) => {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
};

/**
 * 1. Export Report as PDF (jsPDF + autoTable)
 */
export const exportReportToPDF = (options: ReportExportOptions) => {
  const {
    businessName,
    businessAddress,
    businessTaxId,
    reportTitle,
    startDate,
    endDate,
    filenamePrefix,
    headers,
    rows,
    summaryRows,
    columnAlignments
  } = options;

  const doc = new jsPDF({
    orientation: headers.length > 6 ? 'landscape' : 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Primary Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(22, 160, 133); // #16A085
  doc.text(businessName.toUpperCase(), 14, 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  let currentY = 23;
  if (businessAddress) {
    doc.text(businessAddress, 14, currentY);
    currentY += 4.5;
  }
  if (businessTaxId) {
    doc.text(`Tax ID: ${businessTaxId}  |  Currency: Rs (PKR/INR)`, 14, currentY);
    currentY += 4.5;
  }

  // Report Title Badge
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(30, 41, 59);
  doc.text(reportTitle.toUpperCase(), 14, currentY + 3);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  doc.text(`Reporting Period: ${startDate} to ${endDate}`, 14, currentY + 7.5);

  const tableStartY = currentY + 12;

  // Build Column Styles
  const colStyles: Record<number, any> = {};
  headers.forEach((_, idx) => {
    const align = columnAlignments?.[idx] || (idx === 0 ? 'left' : 'right');
    colStyles[idx] = { halign: align };
  });

  autoTable(doc, {
    startY: tableStartY,
    head: [headers],
    body: rows.map(r => r.map(c => String(c ?? ''))),
    theme: 'striped',
    headStyles: {
      fillColor: [22, 160, 133],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
      cellPadding: 2.5
    },
    bodyStyles: {
      textColor: [30, 41, 59],
      fontSize: 8,
      cellPadding: 2.5
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252]
    },
    columnStyles: colStyles,
    margin: { left: 14, right: 14 }
  });

  // Summary / Totals Box if provided
  if (summaryRows && summaryRows.length > 0) {
    const finalY = (doc as any).lastAutoTable?.finalY || 100;
    let sumY = finalY + 6;

    if (sumY > doc.internal.pageSize.getHeight() - 30) {
      doc.addPage();
      sumY = 20;
    }

    doc.setFillColor(241, 245, 249);
    doc.roundedRect(pageWidth - 90, sumY, 76, summaryRows.length * 5.5 + 4, 1.5, 1.5, 'F');

    summaryRows.forEach(s => {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(71, 85, 105);
      doc.text(s.label, pageWidth - 86, sumY + 4.5);
      doc.text(String(s.value), pageWidth - 18, sumY + 4.5, { align: 'right' });
      sumY += 5.5;
    });
  }

  // Footer on all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Generated by Alfatechlink Accounting on ${new Date().toLocaleDateString()} | Page ${i} of ${totalPages}`,
      pageWidth / 2,
      doc.internal.pageSize.getHeight() - 8,
      { align: 'center' }
    );
  }

  const cleanFilename = `${filenamePrefix}_${startDate}_${endDate}.pdf`;
  doc.save(cleanFilename);
};

/**
 * 2. Export Report as Excel (.xlsx) using SheetJS
 */
export const exportReportToExcel = (options: ReportExportOptions) => {
  const {
    businessName,
    businessAddress,
    businessTaxId,
    reportTitle,
    startDate,
    endDate,
    filenamePrefix,
    headers,
    rows,
    summaryRows
  } = options;

  // Construct sheet data
  const sheetData: any[][] = [];

  // Metadata rows
  sheetData.push([businessName]);
  if (businessAddress) sheetData.push([businessAddress]);
  if (businessTaxId) sheetData.push([`Tax ID: ${businessTaxId}`]);
  sheetData.push([reportTitle]);
  sheetData.push([`Period: ${startDate} to ${endDate}`]);
  sheetData.push([]); // Empty row

  // Header Row
  sheetData.push(headers);

  // Data rows
  rows.forEach(r => {
    sheetData.push(r);
  });

  // Summary rows
  if (summaryRows && summaryRows.length > 0) {
    sheetData.push([]);
    summaryRows.forEach(s => {
      sheetData.push([s.label, '', '', '', s.value]);
    });
  }

  // Create worksheet
  const ws = XLSX.utils.aoa_to_sheet(sheetData);

  // Auto calculate column widths
  const colWidths = headers.map((h, colIdx) => {
    let maxLen = String(h).length;
    rows.forEach(r => {
      const cellVal = String(r[colIdx] ?? '');
      if (cellVal.length > maxLen) maxLen = cellVal.length;
    });
    return { wch: Math.min(Math.max(maxLen + 3, 12), 40) };
  });
  ws['!cols'] = colWidths;

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Report');

  const outBuffer = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
  const blob = new Blob([outBuffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  const cleanFilename = `${filenamePrefix}_${startDate}_${endDate}.xlsx`;
  downloadBlob(blob, cleanFilename);
};

/**
 * 3. Export Report as Word (.docx) using docx library
 */
export const exportReportToDocx = async (options: ReportExportOptions) => {
  const {
    businessName,
    businessAddress,
    businessTaxId,
    reportTitle,
    startDate,
    endDate,
    filenamePrefix,
    headers,
    rows,
    summaryRows
  } = options;

  const tableHeaderRow = new TableRow({
    tableHeader: true,
    children: headers.map(
      h =>
        new TableCell({
          shading: {
            type: ShadingType.CLEAR,
            fill: '16A085'
          },
          children: [
            new Paragraph({
              alignment: AlignmentType.CENTER,
              children: [
                new TextRun({
                  text: h,
                  bold: true,
                  color: 'FFFFFF',
                  size: 18
                })
              ]
            })
          ]
        })
    )
  });

  const tableDataRows = rows.map((r, rowIndex) => {
    return new TableRow({
      children: r.map(cell => {
        return new TableCell({
          shading: {
            type: ShadingType.CLEAR,
            fill: rowIndex % 2 === 0 ? 'FFFFFF' : 'F8FAFC'
          },
          children: [
            new Paragraph({
              children: [
                new TextRun({
                  text: String(cell ?? ''),
                  size: 18,
                  color: '1E293B'
                })
              ]
            })
          ]
        });
      })
    });
  });

  const tableChildren = [tableHeaderRow, ...tableDataRows];

  if (summaryRows && summaryRows.length > 0) {
    summaryRows.forEach(s => {
      tableChildren.push(
        new TableRow({
          children: [
            new TableCell({
              columnSpan: Math.max(1, headers.length - 1),
              shading: {
                type: ShadingType.CLEAR,
                fill: 'F1F5F9'
              },
              children: [
                new Paragraph({
                  alignment: AlignmentType.RIGHT,
                  children: [
                    new TextRun({
                      text: s.label,
                      bold: true,
                      size: 18
                    })
                  ]
                })
              ]
            }),
            new TableCell({
              shading: {
                type: ShadingType.CLEAR,
                fill: 'F1F5F9'
              },
              children: [
                new Paragraph({
                  alignment: AlignmentType.RIGHT,
                  children: [
                    new TextRun({
                      text: String(s.value),
                      bold: true,
                      size: 18,
                      color: '0E7C66'
                    })
                  ]
                })
              ]
            })
          ]
        })
      );
    });
  }

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: [
          new Paragraph({
            heading: HeadingLevel.HEADING_1,
            children: [
              new TextRun({
                text: businessName.toUpperCase(),
                bold: true,
                color: '16A085',
                size: 32
              })
            ]
          }),
          ...(businessAddress
            ? [
                new Paragraph({
                  children: [
                    new TextRun({
                      text: businessAddress,
                      color: '64748B',
                      size: 18
                    })
                  ]
                })
              ]
            : []),
          ...(businessTaxId
            ? [
                new Paragraph({
                  children: [
                    new TextRun({
                      text: `Tax ID: ${businessTaxId} | Currency: Rs`,
                      color: '64748B',
                      size: 18
                    })
                  ]
                })
              ]
            : []),
          new Paragraph({
            children: [
              new TextRun({
                text: reportTitle.toUpperCase(),
                bold: true,
                size: 24,
                color: '1E293B'
              })
            ],
            spacing: { before: 200, after: 100 }
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: `Period: ${startDate} to ${endDate}`,
                italics: true,
                color: '64748B',
                size: 18
              })
            ],
            spacing: { after: 200 }
          }),
          new Table({
            width: {
              size: 100,
              type: WidthType.PERCENTAGE
            },
            rows: tableChildren
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: `Generated by Alfatechlink Accounting on ${new Date().toLocaleDateString()}`,
                color: '94A3B8',
                size: 14
              })
            ],
            spacing: { before: 300 }
          })
        ]
      }
    ]
  });

  const blob = await Packer.toBlob(doc);
  const cleanFilename = `${filenamePrefix}_${startDate}_${endDate}.docx`;
  downloadBlob(blob, cleanFilename);
};

/**
 * 4. Export Report as CSV
 */
export const exportReportToCSV = (options: ReportExportOptions) => {
  const { filenamePrefix, startDate, endDate, headers, rows, summaryRows } = options;
  const csvRows: string[][] = [
    headers.map(h => `"${String(h).replace(/"/g, '""')}"`)
  ];
  rows.forEach(r => {
    csvRows.push(r.map(c => `"${String(c ?? '').replace(/"/g, '""')}"`));
  });
  if (summaryRows && summaryRows.length > 0) {
    csvRows.push([]);
    summaryRows.forEach(s => {
      csvRows.push([`"${s.label}"`, `"${s.value}"`]);
    });
  }
  const csvContent = 'data:text/csv;charset=utf-8,\uFEFF' + csvRows.map(e => e.join(',')).join('\n');
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement('a');
  link.setAttribute('href', encodedUri);
  link.setAttribute('download', `${filenamePrefix}_${startDate}_${endDate}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
};

/**
 * 5. Reliable Print Handler using isolated iframe & fallback
 */
export const printReportHtml = (options: ReportExportOptions) => {
  const {
    businessName,
    businessAddress,
    businessTaxId,
    reportTitle,
    startDate,
    endDate,
    headers,
    rows,
    summaryRows,
    columnAlignments
  } = options;

  try {
    const iframe = document.createElement('iframe');
    iframe.style.position = 'fixed';
    iframe.style.right = '0';
    iframe.style.bottom = '0';
    iframe.style.width = '0';
    iframe.style.height = '0';
    iframe.style.border = '0';
    iframe.style.opacity = '0';
    iframe.style.pointerEvents = 'none';
    document.body.appendChild(iframe);

    const doc = iframe.contentWindow?.document || iframe.contentDocument;
    if (!doc) {
      window.print();
      return;
    }

    const colAlign = (idx: number) => columnAlignments?.[idx] || (idx === 0 ? 'left' : 'right');

    const tableHeadersHtml = headers.map((h, i) =>
      `<th style="text-align: ${colAlign(i)}; padding: 8px 10px; background-color: #16A085; color: #ffffff; font-weight: 700; font-size: 11px; text-transform: uppercase; border: 1px solid #16A085;">${h}</th>`
    ).join('');

    const tableRowsHtml = rows.map((r, rowIdx) => {
      const bg = rowIdx % 2 === 0 ? '#ffffff' : '#f8fafc';
      const cells = r.map((cell, colIdx) =>
        `<td style="text-align: ${colAlign(colIdx)}; padding: 7px 10px; font-size: 11px; border-bottom: 1px solid #e2e8f0; ${colAlign(colIdx) === 'right' ? 'font-family: monospace;' : ''}">${String(cell ?? '')}</td>`
      ).join('');
      return `<tr style="background-color: ${bg};">${cells}</tr>`;
    }).join('');

    let summaryHtml = '';
    if (summaryRows && summaryRows.length > 0) {
      const summaryItems = summaryRows.map(s =>
        `<div style="display: flex; justify-content: space-between; padding: 4px 0; border-bottom: 1px dashed #cbd5e1; font-size: 11px;">
           <span style="font-weight: 600; color: #475569;">${s.label}:</span>
           <span style="font-weight: 700; font-family: monospace; color: #0f172a;">${s.value}</span>
         </div>`
      ).join('');
      summaryHtml = `
        <div style="margin-top: 16px; margin-left: auto; width: 320px; background: #f8fafc; border: 1px solid #cbd5e1; border-radius: 6px; padding: 10px 14px; page-break-inside: avoid;">
          ${summaryItems}
        </div>
      `;
    }

    const html = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${reportTitle} - ${businessName}</title>
  <style>
    @page { margin: 12mm; size: auto; }
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Arial, sans-serif;
      color: #1e293b;
      margin: 0;
      padding: 16px;
      background: #ffffff;
      -webkit-print-color-adjust: exact !important;
      print-color-adjust: exact !important;
    }
    table { width: 100%; border-collapse: collapse; margin-top: 14px; }
    tr { page-break-inside: avoid; }
  </style>
</head>
<body>
  <div style="border-bottom: 2px solid #16A085; padding-bottom: 12px; margin-bottom: 14px; display: flex; justify-content: space-between; align-items: flex-start;">
    <div>
      <div style="font-size: 18px; font-weight: 800; color: #16A085; text-transform: uppercase;">${businessName}</div>
      ${businessAddress ? `<div style="font-size: 11px; color: #64748b; margin-top: 3px;">${businessAddress}</div>` : ''}
      ${businessTaxId ? `<div style="font-size: 11px; color: #64748b;">Tax ID: ${businessTaxId} | Currency: Rs</div>` : ''}
    </div>
    <div style="text-align: right;">
      <div style="font-size: 15px; font-weight: 800; color: #0f172a; text-transform: uppercase;">${reportTitle}</div>
      <div style="font-size: 11px; font-family: monospace; color: #64748b; margin-top: 3px;">Period: ${startDate} to ${endDate}</div>
    </div>
  </div>

  <table>
    <thead>
      <tr>${tableHeadersHtml}</tr>
    </thead>
    <tbody>
      ${tableRowsHtml}
    </tbody>
  </table>

  ${summaryHtml}

  <div style="margin-top: 24px; border-top: 1px solid #e2e8f0; padding-top: 8px; font-size: 10px; color: #94A3B8; text-align: center;">
    Generated by Alfatechlink Accounting on ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}
  </div>
</body>
</html>`;

    doc.open();
    doc.write(html);
    doc.close();

    setTimeout(() => {
      try {
        iframe.contentWindow?.focus();
        iframe.contentWindow?.print();
      } catch (err) {
        console.warn('Iframe print error, falling back to window.print', err);
        window.print();
      }
      setTimeout(() => {
        if (iframe.parentNode) {
          document.body.removeChild(iframe);
        }
      }, 3000);
    }, 250);
  } catch (err) {
    console.error('Print failed:', err);
    window.print();
  }
};

/**
 * 6. Legacy / Direct Print Document Helper
 */
export const printReportDocument = (reportTitle: string) => {
  try {
    const originalTitle = document.title;
    document.title = `${reportTitle} - Alfatechlink`;
    window.focus();
    window.print();
    setTimeout(() => {
      document.title = originalTitle;
    }, 1500);
  } catch (e) {
    console.error('Print failed:', e);
    window.print();
  }
};
